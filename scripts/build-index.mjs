// Generates src/assets/names.ts from the SVG folders so the TypeScript
// asset names can never drift out of sync with the files on disk.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ASSETS = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets');
const SVG = join(ASSETS, 'svg');

const groups = readdirSync(SVG, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const body = groups
  .map((g) => {
    const names = readdirSync(join(SVG, g))
      .filter((f) => f.endsWith('.svg'))
      .map((f) => f.slice(0, -4))
      .sort();
    return `  ${JSON.stringify(g)}: [\n${names.map((n) => `    ${JSON.stringify(n)},`).join('\n')}\n  ],`;
  })
  .join('\n');

writeFileSync(
  join(ASSETS, 'names.ts'),
  `// AUTO-GENERATED by scripts/build-index.mjs. Do not edit by hand.
export const ASSET_GROUPS = {
${body}
} as const;

export type AssetGroup = keyof typeof ASSET_GROUPS;
export type AssetName = (typeof ASSET_GROUPS)[AssetGroup][number];
`
);
console.log('names.ts written');
